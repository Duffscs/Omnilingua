using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Omnilingua.Dotnet.SourceGen;

public sealed partial class PluginContractGenerator {
    private static void GeneratePlugin(SourceProductionContext output, ClassDeclarationSyntax declaration, Compilation compilation) {
        SemanticModel semantic = compilation.GetSemanticModel(declaration.SyntaxTree);
        if (semantic.GetDeclaredSymbol(declaration) is not INamedTypeSymbol plugin) { return; }
        AttributeData[] attributes = plugin.GetAttributes().Where(attribute => attribute.AttributeClass?.ToDisplayString() is "Omnilingua.Dotnet.PluginExportAttribute" or "Omnilingua.Dotnet.PluginImportAttribute").ToArray();
        if (attributes.Length == 0) { return; }
        ClassDeclarationSyntax first = plugin.DeclaringSyntaxReferences.Select(reference => reference.GetSyntax()).OfType<ClassDeclarationSyntax>().First(part => part.AttributeLists.Count > 0);
        if (first.SyntaxTree != declaration.SyntaxTree || first.Span != declaration.Span) { return; }
        Location location = declaration.GetLocation();
        void Error(string message) => output.ReportDiagnostic(Diagnostic.Create(InvalidContract, location, message));
        if (plugin.IsGenericType || plugin.ContainingType is not null || plugin.IsAbstract || plugin.IsStatic ||
            plugin.DeclaringSyntaxReferences.Any(reference => !((ClassDeclarationSyntax)reference.GetSyntax()).Modifiers.Any(SyntaxKind.PartialKeyword))) {
            Error("La classe du plugin doit être partial, concrète, non générique et non imbriquée."); return;
        }
        if (plugin.GetMembers("GetMetadata").Length > 0) { Error("GetMetadata est généré : retirer sa déclaration manuelle."); return; }
        if (!plugin.AllInterfaces.Any(type => type.ToDisplayString() == "Omnilingua.Dotnet.IPlugin")) {
            Error("La classe annotée doit implémenter Omnilingua.Dotnet.IPlugin."); return;
        }
        string ns = plugin.ContainingNamespace.IsGlobalNamespace ? "" : plugin.ContainingNamespace.ToDisplayString();
        List<string> exports = [], imports = [], bindings = [];
        List<(ContractModel Model, string Helper)> helpers = [];
        HashSet<string> names = new(StringComparer.Ordinal);
        HashSet<string> importedTypes = new(StringComparer.Ordinal);
        foreach (AttributeData attribute in attributes) {
            if (attribute.ConstructorArguments.Length != 1 || attribute.ConstructorArguments[0].Value is not INamedTypeSymbol contractType) {
                Error("PluginExport et PluginImport attendent typeof(une interface)."); return;
            }
            AnalysisResult result = PrepareContract(contractType, attribute, output.CancellationToken);
            if (result.Error is not null || result.Contract is null) { Error(result.Error ?? "Contrat invalide."); return; }
            ContractModel contract = result.Contract with { Namespace = ns };
            bool export = attribute.AttributeClass!.Name == "PluginExportAttribute";
            if (!names.Add((export ? "export:" : "import:") + contract.ContractName)) { Error($"Contrat dupliqué : {contract.ContractName}."); return; }
            string helper = "__" + plugin.Name + "Contract" + helpers.Count;
            helpers.Add((contract, helper));
            if (export) {
                exports.Add(helper + ".Metadata.Description");
                bindings.Add($"new {Sdk}ManagedServiceExport(typeof({contract.InterfaceName}), {helper}.Metadata.Description, implementation => {helper}.Metadata.Export(({contract.InterfaceName})implementation))");
            } else {
                if (!importedTypes.Add(contract.InterfaceName)) { Error("Une interface locale ne peut pas recevoir plusieurs fournisseurs."); return; }
                bool optional = attribute.NamedArguments.Any(pair => pair.Key == "Optional" && pair.Value.Value is true);
                imports.Add(helper + ".Metadata.Require(optional: " + (optional ? "true" : "false") + ")");
            }
        }
        string hint = (ns + "." + plugin.Name);
        CodeBuilder builder = new();
        builder.AddLine("// <auto-generated/>").AddLine("#nullable enable");
        if (ns.Length > 0) { builder.AddLine("namespace " + ns + ";"); }
        builder.AddClass(Escape(plugin.Name), new() { Visibility = plugin.DeclaredAccessibility == Accessibility.Public ? Visibility.Public : Visibility.Internal, Modifiers = "partial" });
        builder.AddLine("/// <summary>Décrit automatiquement les contrats importés et exportés du plugin.</summary>");
        builder.AddMethod("GetMetadata", new() { ReturnType = Sdk + "PluginMetadata" })
            .AddLine($"return new {Sdk}PluginMetadata([], [{string.Join(", ", exports)}], [{string.Join(", ", imports)}], [{string.Join(", ", bindings)}]);")
            .EndBlock().EndBlock();
        output.AddSource(hint + ".Metadata.g.cs", builder.Build());
        foreach ((ContractModel model, string helper) in helpers) { output.AddSource(hint + "." + helper + ".g.cs", GenerateContract(model, helper)); }
    }
}
