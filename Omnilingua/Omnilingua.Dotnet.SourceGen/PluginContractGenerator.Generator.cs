using Microsoft.CodeAnalysis.CSharp;

namespace Omnilingua.Dotnet.SourceGen;

public sealed partial class PluginContractGenerator {
    private const string Sdk = "global::Omnilingua.Dotnet.";
    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, true);

    private static string GenerateContract(ContractModel contract, string helperName) {
        CodeBuilder builder = new();
        builder.AddLine("// <auto-generated/>").AddLine("#nullable enable");
        if (contract.Namespace.Length > 0) { builder.AddLine($"namespace {contract.Namespace};"); }
        builder.AddClass(helperName, new() { Visibility = Visibility.Internal, Modifiers = "static" });
        Dictionary<string, TypeModel> types = contract.Types.ToDictionary(type => type.Id);
        foreach (TypeModel type in contract.Types) {
            string expression;
            if (type.Kind == "Record") {
                builder.BeginBlock($"private static readonly {Sdk}AbiTypeDescription {type.Id} = {Sdk}AbiTypeLayouts.Record({Literal(type.Name)}, new {Sdk}AbiMemberDefinition[]");
                foreach (FieldModel field in type.Fields) { builder.AddLine($"new {Sdk}AbiMemberDefinition({Literal(field.Name)}, {field.TypeId}, {field.Optional.ToString().ToLowerInvariant()}),"); }
                builder.EndBlock().AddLine(");");
            } else {
                expression = type.Kind is "Array" or "Sequence" ?
                    $"{Sdk}AbiTypeLayouts.{type.Kind}({Literal(type.Name)}, {type.ElementId})" :
                    $"{Sdk}AbiTypeLayouts.Primitive({Sdk}AbiKind.{type.Kind}, {Literal(type.Name)}" +
                        (type.EnumValues.Length == 0 ? ")" : $", new {Sdk}AbiEnumValueDescription[] {{ " +
                            string.Join(", ", type.EnumValues.Select(value => $"new {Sdk}AbiEnumValueDescription({Literal(value.Name)}, {Literal(value.Value)})")) + " })");
                builder.AddField(Sdk + "AbiTypeDescription", type.Id, new() { Visibility = Visibility.Private, Modifiers = "static readonly", InitialValue = expression });
            }
        }
        builder.AddField($"{Sdk}AbiTypeDescription[]", "_generatedTypes", new() {
            Visibility = Visibility.Private, Modifiers = "static readonly", InitialValue = $"new {Sdk}AbiTypeDescription[] {{ {string.Join(", ", contract.Types.Select(type => type.Id))} }}"
        });
        string names = string.Join(", ", contract.Methods.Select(method => Literal(method.Name)));
        builder.BeginBlock($"private static readonly {Sdk}ContractDescription _generatedContract = new {Sdk}ContractDescription({Literal(contract.ContractName)}, new string[] {{ {names} }}, {contract.Version}u, new {Sdk}AbiMethodDescription[]");
        foreach (MethodModel method in contract.Methods) {
            string parameters = string.Join(", ", method.Parameters.Select(parameter => $"new {Sdk}AbiParameterDescription({Literal(parameter.Name)}, {parameter.TypeId}, {Passing(types[parameter.TypeId], parameter.Out)})"));
            builder.AddLine($"new {Sdk}AbiMethodDescription({Literal(method.Name)}, {method.ReturnId}, {Passing(types[method.ReturnId], false)}, new {Sdk}AbiParameterDescription[] {{ {parameters} }}),");
        }
        builder.EndBlock().AddLine(", Types: _generatedTypes);");
        builder.AddLine("/// <summary>Contrat utilisable pour demander une injection ou publier une implementation.</summary>");
        builder.AddLine($"public static {Sdk}PluginContractMetadata<{contract.InterfaceName}> Metadata {{ get; }} = new(_generatedContract, BindGeneratedExport);");
        builder.AddMethod("BindGeneratedExport", new() { Visibility = Visibility.Private, Modifiers = "static", ReturnType = Sdk + "ManagedContractExport", Parameters = [(contract.InterfaceName, "implementation")] });
        builder.BeginBlock($"return new {Sdk}ManagedContractExport(_generatedContract, new {Sdk}ManagedMethodExport[]");
        for (int index = 0; index < contract.Methods.Length; index++) {
            MethodModel method = contract.Methods[index];
            string parameterTypes = string.Join(", ", method.Parameters.Select(parameter => $"typeof({parameter.Type})"));
            builder.BeginBlock($"new {Sdk}ManagedMethodExport(_generatedContract.Signatures![{index}], typeof({method.ReturnType}), new global::System.Type[] {{ {parameterTypes} }}, arguments =>");
            for (int parameterIndex = 0; parameterIndex < method.Parameters.Length; parameterIndex++) {
                ParameterModel parameter = method.Parameters[parameterIndex];
                if (parameter.Out) {
                    string suffix = types[parameter.TypeId].Kind is "Record" or "Array" or "Sequence" or "Utf8" ? "?" : "";
                    builder.AddLine($"{parameter.Type}{suffix} output{parameterIndex};");
                }
            }
            string arguments = string.Join(", ", method.Parameters.Select((parameter, parameterIndex) => parameter.Out ? $"out output{parameterIndex}" : $"({parameter.Type})arguments[{parameterIndex}]!"));
            string target = "implementation";
            bool returnsVoid = types[method.ReturnId].Kind == "Void";
            builder.AddLine((returnsVoid ? "" : "object? result = ") + $"{target}.{method.EscapedName}({arguments});");
            for (int parameterIndex = 0; parameterIndex < method.Parameters.Length; parameterIndex++) {
                if (method.Parameters[parameterIndex].Out) { builder.AddLine($"arguments[{parameterIndex}] = output{parameterIndex};"); }
            }
            builder.AddLine(returnsVoid ? "return null;" : "return result;").EndBlock().AddLine("),");
        }
        builder.EndBlock().AddLine(");").EndBlock();
        builder.EndBlock();
        return builder.Build();
    }

    private static string Passing(TypeModel type, bool output) => Sdk + "AbiPassing." + (output ? "Out" : type.Kind is "Record" or "Sequence" ? "Reference" : "Value");
}
