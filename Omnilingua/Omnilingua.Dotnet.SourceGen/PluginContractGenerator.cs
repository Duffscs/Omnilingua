using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Omnilingua.Dotnet.SourceGen;

/// <summary>Déduit les métadonnées et liaisons des interfaces de contrats annotées.</summary>
[Generator(LanguageNames.CSharp)]
public sealed partial class PluginContractGenerator : IIncrementalGenerator {
    private static readonly DiagnosticDescriptor InvalidContract = new("HSG001", "Contrat non générable", "{0}", "Omnilingua.Dotnet", DiagnosticSeverity.Error, true);

    /// <summary>Crée l’attribut puis enregistre l’analyse sémantique et la génération.</summary>
    public void Initialize(IncrementalGeneratorInitializationContext context) {
        context.RegisterPostInitializationOutput(static output => output.AddSource("PluginServicesAttributes.g.cs", """
            // <auto-generated/>
            #nullable enable
            namespace Omnilingua.Dotnet {
                /// <summary>Annonce un contrat fourni par les objets exportes du plugin.</summary>
                [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
                internal sealed class PluginExportAttribute(global::System.Type contractType) : global::System.Attribute {
                    public global::System.Type ContractType { get; } = contractType;
                    public string? Name { get; set; }
                    public uint Version { get; set; } = 1;
                }
                /// <summary>Annonce un contrat demande au fournisseur configure.</summary>
                [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
                internal sealed class PluginImportAttribute(global::System.Type contractType) : global::System.Attribute {
                    public global::System.Type ContractType { get; } = contractType;
                    public string? Name { get; set; }
                    public uint Version { get; set; } = 1;
                    public bool Optional { get; set; }
                }
            }
            """));
        IncrementalValuesProvider<Microsoft.CodeAnalysis.CSharp.Syntax.ClassDeclarationSyntax> plugins = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is Microsoft.CodeAnalysis.CSharp.Syntax.ClassDeclarationSyntax declaration && declaration.AttributeLists.Count > 0,
            static (syntax, _) => (Microsoft.CodeAnalysis.CSharp.Syntax.ClassDeclarationSyntax)syntax.Node);
        context.RegisterSourceOutput(plugins.Combine(context.CompilationProvider), static (output, item) => GeneratePlugin(output, item.Left, item.Right));
    }
}
